"""
Keep a collection's human landing page and published figure contract together.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from witful.awareness.models import FIGURES as AWARENESS_FIGURES
from witful.reflection.plotting import FIGURES as REVIEW_FIGURES

if TYPE_CHECKING:
    from witful.collection.models import Config

# Export sharing remains separately opted in; collection publication also owns the Life overview.
FIGURES = {
    **AWARENESS_FIGURES,
    "life": ("life", "Life: choices and revisions"),
    **{name: ("reflection", title) for name, title in REVIEW_FIGURES.items()},
}
CAPTIONS = {
    "knowledge-map": "Connections show recorded reuse; the emphasis window highlights current working areas.",
    "knowledge-usage": "Counts describe observed applications, not proficiency or the importance of an idea.",
    "knowledge-hierarchy": "The complete discipline, skill, lesson and insight hierarchy retains the surrounding context.",
    "life": (
        "The left panel shows change per entry: +1 for an accepted choice, 0 for an unchanged-status revision, "
        "and -1 for retirement. Repeated +1 values can be current; totals grow below the plot."
    ),
    "decision-influences": "These concepts are linked to recorded decisions, independently of skill-use counts.",
    "decision-outcomes": "Reviewed outcomes retain evidence and uncertainty rather than inferring success from activity.",
    "decision-context": "Reviews show where a decision's context changed and where further evidence is needed.",
    "toolbox-use": "Only recorded tool applications contribute to these counts.",
    "problem-repertoire": "Observed problems connect specific tasks to broader engineering concepts.",
    "checkpoint-transitions": "Project visits preserve evidence at committed boundaries, including unchanged visits.",
    "checkpoint-comparisons": "Compare recorded project checkpoints without treating commit volume as learning.",
    "instance-comparisons": "Observed execution contexts remain distinct; missing evidence stays visible.",
}


def readme(config: Config, source_digest: str, *, reflection_enabled: bool = True) -> str:
    """
    Render a complete end-user dashboard from explicit disclosure choices.

    Args:
        config (Config): Reviewed repository destination and readable-figure opt-in.
        source_digest (str): SHA-256 of encrypted source bytes, never private record text.
        reflection_enabled (bool): Include periodic-review figures when the source enables them.

    Returns:
        str: Repository-specific Markdown with captions, maintenance links and attribution.
    """
    text = (
        "<!-- Generated by Witful on private main. Configure .config/collection.json; edit the renderer for layout. -->\n\n"
        "# My knowledge collection\n\n"
        "A living record of what I learn, where I apply it, and why I change my mind. "
        "The views below connect reviewed lessons, real applications, decisions and project history.\n\n"
        "<!-- toc:start -->\n**Table of contents**\n\n"
        "- [Current evidence](#current-evidence)\n- [Maintain this collection](#maintain-this-collection)\n"
        "- [Inputs](#inputs)\n- [Credits](#credits)\n<!-- toc:end -->\n\n"
        "To inspect a restored collection, run `witful check`. "
        "[Setup and recovery](docs/private-collections.md) cover the required keys and local restore.\n\n"
        "## Current evidence\n\n"
        f"[Latest refresh](https://github.com/{config.repository}/actions/workflows/ci.yml) | "
        "[Encrypted figures](collection/figures.enc.json)\n\n"
        "Main refreshes the page and figures together after reviewed source records arrive. "
        "PRs and tags do not refresh this dashboard. Lessons and checkpoints do not automatically create Life decisions.\n\n"
        f"Source ciphertext SHA-256: `{source_digest}`.\n\n"
    )
    if config.publish_figures:
        # Preserve an intentional reader order while deriving the publication allowlist from one catalog.
        for number, (name, caption) in enumerate(
            ((name, caption) for name, caption in CAPTIONS.items() if reflection_enabled or name not in REVIEW_FIGURES), 1
        ):
            title = FIGURES[name][1]
            text += f"![{title}](docs/collection/{name}.svg)\n\n**Figure {number}. {title}.** {caption}\n\n"
    else:
        text += (
            "Figures remain encrypted. GitHub cannot display them inline. Restore them locally with:\n\n"
            "```bash\nwitful collection restore --checkout CHECKOUT --key-dir KEYS --output NEW_DIRECTORY --figures\n```\n\n"
        )
    return text + (
        "## Maintain this collection\n\n"
        "Record reviewed teachings and decisions in the restored working collection, then seal the updated sources:\n\n"
        "```bash\nwitful collection seal --checkout CHECKOUT --source COLLECTION --key-dir KEYS\n```\n\n"
        "Commit the named encrypted outputs and push through review to `main`. "
        "[Agent guidance](SKILL.md), [CLI reference](docs/CLI.md), and "
        "[collection operations](docs/private-collections.md) retain the detailed workflows.\n\n"
        "## Inputs\n\n"
        "| Input | Purpose |\n| --- | --- |\n"
        "| `.config/collection.json` | Repository and trust pins; `publish_figures` defaults to `false` |\n"
        "| `collection/sources.enc.json` | Reviewed, signed encrypted records for the current refresh |\n"
        "| `KEYS` | Existing independent encryption and signing key backup; never committed |\n"
        "| `knowledge/reflection.json` | Periodic-review settings inside the encrypted source collection |\n\n"
        "Readable figures disclose their labels, counts and relationships to repository readers. "
        "Approve that audience before enabling them; disabling publication cannot remove earlier Git history.\n\n"
        "## Credits\n\n"
        "Built with [Identity and Witful](https://github.com/astrivant/identity). "
        "[License](LICENSE) and source-level notices retain the project's attribution.\n"
    )
